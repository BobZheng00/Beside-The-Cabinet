"""App icon: the tray's coin with its slot mark, drawn in the cabinet's style (gold gradient, ink outline, a
visible edge like the coins in the cabinet's tray). Each size is drawn on its own so the outline and the slot
stay at least a pixel or two wide when small, rendered with Chrome, and packed into a Windows .ico.

    python tools/art/app_icon.py     # -> src/InsertCoin.Game/icon.ico, icon.png (256 px), art/icon/icon.svg
"""
import struct
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from cozy_cabinet import CHROME, OUT  # noqa: E402

SIZES = [16, 20, 24, 32, 40, 48, 64, 96, 128, 256]     # 20 and 40 are what Windows asks for at 125 % scaling
GOLD = ('<radialGradient id="gold" cx="35%" cy="30%" r="75%"><stop offset="0" stop-color="#FFF3C0"/>'
        '<stop offset="0.5" stop-color="#FFC94D"/><stop offset="1" stop-color="#D38A1C"/></radialGradient>')
EDGE = "#B7791A"


def coin(px):
    """SVG of the coin for an icon of px pixels, drawn in a 256-unit box."""
    unit = 256 / px                                   # icon units per output pixel
    ink = max(10.0, 1.5 * unit)
    edge = max(12.0, 1.3 * unit)                      # how much of the coin's edge shows below its face
    r = 128 - ink / 2 - edge / 2 - max(2.0, 0.5 * unit)
    cx, cy = 128, 128 - edge / 2
    slot_w, slot_h = max(0.2 * r, 2.4 * unit), 1.0 * r
    parts = [f'<defs>{GOLD}</defs>',
             f'<circle cx="{cx}" cy="{cy + edge}" r="{r}" fill="{EDGE}" stroke="{OUT}" stroke-width="{ink}"/>',
             f'<rect x="{cx - r}" y="{cy}" width="{2 * r}" height="{edge}" fill="{EDGE}"/>',
             f'<path d="M{cx - r} {cy} v{edge} M{cx + r} {cy} v{edge}" stroke="{OUT}" stroke-width="{ink}"/>',
             f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="url(#gold)" stroke="{OUT}" stroke-width="{ink}"/>']
    if px >= 48:                                      # a raised rim inside the edge, as on a real coin
        parts.append(f'<circle cx="{cx}" cy="{cy}" r="{0.76 * r}" fill="none" stroke="{EDGE}" stroke-width="{0.06 * r}" opacity="0.75"/>')
    if px >= 32:                                      # a glint, as on the cabinet's gold
        parts.append(f'<ellipse cx="{cx - 0.42 * r}" cy="{cy - 0.48 * r}" rx="{0.2 * r}" ry="{0.11 * r}" '
                     f'transform="rotate(-35 {cx - 0.42 * r} {cy - 0.48 * r})" fill="#FFFFFF" opacity="0.7"/>')
    parts.append(f'<rect x="{cx - slot_w / 2}" y="{cy - slot_h / 2}" width="{slot_w}" height="{slot_h}" '
                 f'rx="{slot_w / 2}" fill="{OUT}"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="{px}" height="{px}">'
            f'<!-- INSERT COIN app icon (generated by tools/art/app_icon.py). Original artwork. -->{"".join(parts)}</svg>\n')


# ---- PNG in and out (no image library needed) ----------------------------------------------------------------------

def read_png(data):
    """Decodes an 8-bit, non-interlaced RGB or RGBA PNG (what Chrome writes) to (width, height, RGBA rows)."""
    pos, chunks = 8, {}
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        chunks.setdefault(kind, []).append(data[pos + 8:pos + 8 + length])
        pos += 12 + length
    width, height, depth, colour = struct.unpack(">IIBB", chunks[b"IHDR"][0][:10])
    assert depth == 8 and colour in (2, 6), (depth, colour)
    channels = 4 if colour == 6 else 3
    raw, stride = zlib.decompress(b"".join(chunks[b"IDAT"])), width * channels
    rows, previous = [], bytearray(stride)
    for y in range(height):
        kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - channels] if i >= channels else 0
            b = previous[i]
            c = previous[i - channels] if i >= channels else 0
            if kind == 1: line[i] = (line[i] + a) & 255
            elif kind == 2: line[i] = (line[i] + b) & 255
            elif kind == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        previous = line
        rows.append(line if channels == 4 else bytearray(b for j in range(width) for b in (*line[3 * j:3 * j + 3], 255)))
    return width, height, rows


def write_png(width, height, rows):
    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))
    raw = b"".join(b"\0" + bytes(row[:4 * width]) for row in rows[:height])
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def render(px, work):
    """The coin at px pixels as RGBA rows. Chrome may not open a window that small, so the shot is cropped."""
    svg, png = work / f"icon-{px}.svg", work / f"icon-{px}.png"
    svg.write_text(coin(px), encoding="utf-8")
    window = max(px, 256)
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                    "--default-background-color=00000000", f"--window-size={window},{window}",
                    f"--screenshot={png}", svg.resolve().as_uri()], check=True, capture_output=True)
    width, height, rows = read_png(png.read_bytes())
    assert width >= px and height >= px, (px, width, height)
    return [row[:4 * px] for row in rows[:px]]


def ico(images):
    """A .ico with every size: 256 as PNG, the rest as 32-bit bitmaps (understood everywhere)."""
    blobs = []
    for px, rows in images:
        if px >= 256:
            blobs.append(write_png(px, px, rows))
            continue
        header = struct.pack("<IiiHHIIiiII", 40, px, 2 * px, 1, 32, 0, 0, 0, 0, 0, 0)
        pixels = b"".join(bytes(b for j in range(px) for b in (row[4 * j + 2], row[4 * j + 1], row[4 * j], row[4 * j + 3]))
                          for row in reversed(rows))
        mask_stride = (px + 31) // 32 * 4
        mask = b""
        for row in reversed(rows):                    # 1 = transparent, for anything that ignores alpha
            bits = bytearray(mask_stride)
            for j in range(px):
                if row[4 * j + 3] == 0:
                    bits[j // 8] |= 0x80 >> (j % 8)
            mask += bytes(bits)
        blobs.append(header + pixels + mask)
    out = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    for (px, _), blob in zip(images, blobs):
        out += struct.pack("<BBBBHHII", px % 256, px % 256, 0, 0, 1, 32, len(blob), offset)
        offset += len(blob)
    return out + b"".join(blobs)


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    game, art = root / "src" / "InsertCoin.Game", root / "art" / "icon"
    art.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        images = [(px, render(px, Path(tmp))) for px in SIZES]
    (game / "icon.ico").write_bytes(ico(images))
    (game / "icon.png").write_bytes(write_png(256, 256, images[-1][1]))
    (art / "icon.svg").write_text(coin(256), encoding="utf-8")
    for px in (16, 32, 48):
        (art / f"icon-{px}.png").write_bytes(write_png(px, px, dict(images)[px]))
    print("wrote", game / "icon.ico", "and", game / "icon.png")
