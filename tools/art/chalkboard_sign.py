"""Generates the Cozy skin's chalkboard sign (art/cozy/sign.svg, and skins/cozy/sign.png with --skin).

A small A-frame chalkboard that stands on the desk beside the cabinet, in the cabinet's style: its outline colour and
stroke, its purple wood, a dark slate board with a little chalk dust, a chalk ledge with a stick of chalk, and the
back leg showing on the right as the cabinet is seen from the front right. The board is blank: the app chalks the
words on it live, in the area BOARD gives (canvas units, as App/ChalkboardSign.cs has them).

    python tools/art/chalkboard_sign.py           # writes art/cozy/sign.svg
    python tools/art/chalkboard_sign.py --skin    # and renders src/InsertCoin.Game/skins/cozy/sign.png
"""
from pathlib import Path

from cozy_cabinet import OUT, STROKE, THIN, SCALE, render_png

W, H = 236, 256                     # the sign's picture, canvas units
BOARD = (28, 22, 180, 166)          # the slate inside the frame: x, y, width, height
FEET = 246                          # where its legs stand on the desk


def sign():
    x, y, w, h = BOARD
    frame = f'<path d="M14 6 H206 L218 {FEET} H198 L194 200 H26 L22 {FEET} H2 Z" fill="url(#wood)" {STROKE}/>'
    back_leg = f'<path d="M204 8 L232 {FEET - 4} H216 L200 40 Z" fill="#3A2E5E" {STROKE}/>'
    board = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="5" fill="url(#slate)" {THIN}/>'
    # chalk dust: a few faint smudges left by earlier words, wiped
    dust = "".join(f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="#E8F2EE" opacity="{o}" transform="rotate({r} {cx} {cy})"/>'
                   for cx, cy, rx, ry, o, r in ((72, 60, 38, 9, 0.05, -8), (150, 120, 44, 10, 0.045, 6),
                                                 (96, 160, 50, 8, 0.04, -3), (164, 52, 22, 6, 0.04, 12)))
    shine = f'<path d="M{x + 6} {y + 6} H{x + 52} L{x + 6} {y + 40} Z" fill="#FFFFFF" opacity="0.05"/>'
    ledge = f'<rect x="20" y="192" width="180" height="10" rx="3" fill="#7462B0" {THIN}/>'
    chalk = (f'<rect x="146" y="185" width="22" height="7" rx="2.5" fill="#F4F1FA" {THIN}/>'
             f'<rect x="58" y="186.5" width="12" height="5.5" rx="2" fill="#F7B6DF" {THIN}/>')
    hinge = f'<rect x="100" y="1.5" width="20" height="9" rx="3" fill="#C6B8F4" {THIN}/>'
    shadow = f'<ellipse cx="{W / 2 + 6}" cy="{FEET}" rx="{W / 2 - 4}" ry="7" fill="#000" opacity="0.32" filter="url(#soft)"/>'
    return shadow + back_leg + frame + board + shine + dust + ledge + chalk + hinge


def document():
    defs = '''<defs>
  <linearGradient id="wood" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#8674C4"/><stop offset="1" stop-color="#6452A0"/></linearGradient>
  <linearGradient id="slate" x1="0" y1="0" x2="0.3" y2="1"><stop offset="0" stop-color="#34433F"/><stop offset="1" stop-color="#26302E"/></linearGradient>
  <filter id="soft" x="-30%" y="-200%" width="160%" height="500%"><feGaussianBlur stdDeviation="3"/></filter>
</defs>'''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">\n'
            f'<!-- INSERT COIN · Cozy skin chalkboard sign (generated by tools/art/chalkboard_sign.py). Original artwork. -->\n'
            f'{defs}\n{sign()}\n</svg>\n')


if __name__ == "__main__":
    import sys
    root = Path(__file__).resolve().parents[2]
    out = root / "art" / "cozy" / "sign.svg"
    out.write_text(document(), encoding="utf-8")
    print(f"wrote {out}")
    if "--skin" in sys.argv:
        render_png(out, root / "src" / "InsertCoin.Game" / "skins" / "cozy" / "sign.png", W, H)
        print(f"rendered skins/cozy/sign.png at {SCALE}x ({W * SCALE}x{H * SCALE}); the board is at {BOARD}, the feet at {FEET}")
